"""Relics that change the math inside a turn, as rules for the solver.

Most relics act at combat/turn start (Strength, block, energy, draw); those already show up in the
live numbers the reader sends, so they need nothing here. These rules cover relics that act *while*
cards are played or at end of turn. Each mirrors its decompiled source (v0.107.1); numbers come from
gamedata.json, live counters (e.g. Kunai._attacksPlayedThisTurn) from the reader."""

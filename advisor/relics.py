# Cards played so far in the simulated turn (block = cards that gave block; exhausted = cards exhausted). A card's
# pick (Acrobatics' discard, True Grit's exhaust) takes cards from hand: tossed = unplayable junk taken, gone = cards
# taken per solver group, lost = score of good cards exhausted for the fight.
Plays = namedtuple("Plays", "attacks skills powers cards block exhausted tossed gone lost", defaults=(0, 0, (), 0))
NO_PLAYS = Plays(0, 0, 0, 0, 0)

IN_TURN_HOOKS = {"ModifyDamageAdditive", "ModifyDamageMultiplicative", "ModifyBlockMultiplicative",
                 "AfterCardPlayed", "BeforeCardPlayed", "BeforeSideTurnEnd"}
MODELED = {"StrikeDummy", "FakeStrikeDummy", "MiniatureCannon", "PenNib", "Vambrace", "ChemicalX",
           "Kunai", "Shuriken", "OrnamentalFan", "Kusarigama", "Nunchaku", "DaughterOfTheWind",
           "LetterOpener", "TuningFork", "LostWisp", "Permafrost", "IvoryTile", "IntimidatingHelmet",
           "Orichalcum", "FakeOrichalcum", "PaelsTears", "CloakClasp", "RippleBasin", "ScreamingFlagon", "StoneCalendar"}


class Relics:
    def __init__(self, relics, data):
        self.counters = {r["name"]: r.get("counters", {}) for r in relics}
        self.data = data  # gamedata["relics"]

    def __contains__(self, name):
        return name in self.counters

    def var(self, relic, key):
        return self.data.get(relic, {}).get("vars", {}).get(key, 0)

    def count(self, relic, field):
        return self.counters.get(relic, {}).get(field, 0)

    def every(self, relic, field, done):
        """True if this play is the Nth (relic's Cards var) counting the live counter."""
        n = int(self.var(relic, "Cards")) or 1
        return relic in self and (self.count(relic, field) + done) % n == 0

    def unmodeled(self):
        return [n for n in self.counters if n not in MODELED
                and IN_TURN_HOOKS & set(self.data.get(n, {}).get("hooks", []))]


def dmg_add(card, R):
    add = 0
    if "Strike" in card["name"]:  # ponytail: CardTag.Strike approximated by name
        add += sum(R.var(n, "ExtraDamage") for n in ("StrikeDummy", "FakeStrikeDummy") if n in R)
    if "MiniatureCannon" in R and card["upgraded"]:
        add += R.var("MiniatureCannon", "ExtraDamage")
    return add


def dmg_mult(card, R, before):
    """before = Plays before this card. Pen Nib doubles every 10th attack."""
    if "PenNib" in R and card["type"] == "Attack" and (R.count("PenNib", "_attacksPlayed") + before.attacks) % 10 == 9:
        return 2
    return 1


def block_mult(R, before):
    """Vambrace doubles the first block gained from a card each combat."""
    if "Vambrace" in R and not R.count("Vambrace", "_blockGainedThisCombat") and before.block == 0:
        return 2
    return 1


def x_bonus(R):
    return int(R.var("ChemicalX", "Increase")) if "ChemicalX" in R else 0


def after_play(card, spent, R, p):
    """Effects triggered by playing `card` (p = Plays including it). Keys: str dex block energy dmg_all dmg_one."""
    fx = {}

    def add(key, n):
        fx[key] = fx.get(key, 0) + n

    t = card["type"]
    if t == "Attack":
        if R.every("Kunai", "_attacksPlayedThisTurn", p.attacks):
            add("dex", R.var("Kunai", "DexterityPower"))
        if R.every("Shuriken", "_attacksPlayedThisTurn", p.attacks):
            add("str", R.var("Shuriken", "StrengthPower"))
        if R.every("OrnamentalFan", "_attacksPlayedThisTurn", p.attacks):
            add("block", R.var("OrnamentalFan", "Block"))
        if R.every("Kusarigama", "_attacksPlayedThisTurn", p.attacks):
            add("dmg_one", R.var("Kusarigama", "Damage"))  # random enemy in game
        if R.every("Nunchaku", "_attacksPlayed", p.attacks):
            add("energy", R.var("Nunchaku", "Energy"))
        if "DaughterOfTheWind" in R:
            add("block", R.var("DaughterOfTheWind", "Block"))
    elif t == "Skill":
        if R.every("LetterOpener", "_skillsPlayedThisTurn", p.skills):
            add("dmg_all", R.var("LetterOpener", "Damage"))
        if "TuningFork" in R and R.count("TuningFork", "_skillsPlayed") + p.skills == int(R.var("TuningFork", "Cards")):
            add("block", R.var("TuningFork", "Block"))
    elif t == "Power":
        if "LostWisp" in R:
            add("dmg_all", R.var("LostWisp", "Damage"))
        if "Permafrost" in R and not R.count("Permafrost", "_activatedThisCombat") and p.powers == 1:
            add("block", R.var("Permafrost", "Block"))
    if "IvoryTile" in R and spent >= R.var("IvoryTile", "EnergyThreshold"):
        add("energy", R.var("IvoryTile", "Energy"))
    if "IntimidatingHelmet" in R and spent >= R.var("IntimidatingHelmet", "Energy"):
        add("block", R.var("IntimidatingHelmet", "Block"))
    return fx


def end_turn(R, block, hand_left, turn, p):
    """(extra block, damage to all enemies) from end-of-turn relics."""
    extra, dmg = 0, 0
    if block == 0:  # Orichalcum checks block before the other end-of-turn effects
        extra += sum(R.var(n, "Block") for n in ("Orichalcum", "FakeOrichalcum") if n in R)
    if "CloakClasp" in R:
        extra += hand_left * R.var("CloakClasp", "Block")
    if "RippleBasin" in R and p.attacks == 0:  # ponytail: only counts attacks in the simulated part of the turn
        extra += R.var("RippleBasin", "Block")
    if "ScreamingFlagon" in R and hand_left == 0:
        dmg += R.var("ScreamingFlagon", "Damage")
    if "StoneCalendar" in R and turn == R.var("StoneCalendar", "DamageTurn"):
        dmg += R.var("StoneCalendar", "Damage")
    return extra, dmg
